// Icons for Pele's `icons` option (architecture services, groups, …): a name maps to render/icons/<name>.svg
// when there is one, else Carbon's icon of that name (@carbon/icons, 32px set), else nothing and Pele
// draws its own. Pele wraps the markup in a 24px stroked frame, so each icon goes in as a nested
// <svg> with its own viewBox, filled in the text colour.
//
//   import { iconsFor } from './icons.mjs'   iconsFor(mermaidSource) -> { name: markup }
//   node icons.mjs preview.html > preview-icons.js   the map for every name the preview uses
import { existsSync, readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const sources = [join(here, 'icons'), join(here, 'node_modules/@carbon/icons/svg/32')]

export function icon(name) {
  if (!/^[\w.-]+$/.test(name)) return undefined
  const file = sources.map((dir) => join(dir, `${name}.svg`)).find(existsSync)
  if (!file) return undefined
  const svg = readFileSync(file, 'utf8').replace(/<\?xml[^>]*>/, '').trim()
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1] ?? '0 0 32 32'
  const body = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
  return `<svg viewBox="${viewBox}" width="24" height="24" fill="currentColor" stroke="none">${body}</svg>`
}

// Every name in parentheses (`service db(data--base)[…]`, `group box(cloud)[…]`) with an icon.
export function iconsFor(source) {
  const names = new Set([...source.matchAll(/\(([\w.-]+)\)/g)].map((m) => m[1]))
  return Object.fromEntries([...names].flatMap((name) => {
    const markup = icon(name)
    return markup ? [[name, markup]] : []
  }))
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = process.argv.slice(2).map((file) => readFileSync(file, 'utf8')).join('\n')
  process.stdout.write(`// Generated by: node icons.mjs preview.html > preview-icons.js\nwindow.ctreeIcons = ${JSON.stringify(iconsFor(text), null, 1)}\n`)
}
